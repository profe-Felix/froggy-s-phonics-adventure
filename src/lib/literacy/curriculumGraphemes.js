function normalizeGrapheme(value) {
  return String(value || '')
    .trim()
    .toLowerCase()
    .normalize('NFC');
}

function uniqueGraphemes(items) {
  const seen = new Set();

  return (items || []).filter((item) => {
    const normalized =
      normalizeGrapheme(item);

    if (
      !normalized ||
      seen.has(normalized)
    ) {
      return false;
    }

    seen.add(normalized);

    return true;
  });
}

function parseCurriculumKey(key) {
  const match =
    /^M(\d+)\.L(\d+)$/i.exec(
      String(key || '').trim()
    );

  if (!match) {
    return null;
  }

  return {
    module_number:
      Number(match[1]),

    curriculum_lesson_number:
      Number(match[2]),
  };
}

export const ES_GRAPHEME_SEQUENCE =
  Object.entries(ES_GRAPHEME_CHART)
    .map(([key, graphemes]) => {
      const position =
        parseCurriculumKey(key);

      if (!position) {
        return null;
      }

      return {
        ...position,
        graphemes:
          uniqueGraphemes(graphemes),
      };
    })
    .filter(Boolean);

export function compareCurriculumPositions(
  first,
  second
) {
  const firstModule = Number(
    first?.module_number || 0
  );

  const secondModule = Number(
    second?.module_number || 0
  );

  if (firstModule !== secondModule) {
    return firstModule - secondModule;
  }

  return (
    Number(
      first?.curriculum_lesson_number || 0
    ) -
    Number(
      second?.curriculum_lesson_number || 0
    )
  );
}

export function getNewGraphemesAt({
  moduleNumber,
  lessonNumber,
}) {
  const key =
    `M${Number(moduleNumber)}.` +
    `L${Number(lessonNumber)}`;

  return uniqueGraphemes(
    ES_GRAPHEME_CHART[key] || []
  );
}

export function getIntroducedGraphemesThrough({
  moduleNumber,
  lessonNumber,
}) {
  const cutoff = {
    module_number:
      Number(moduleNumber) || 0,

    curriculum_lesson_number:
      Number(lessonNumber) || 0,
  };

  const introduced =
    ES_GRAPHEME_SEQUENCE
      .filter(
        (entry) =>
          compareCurriculumPositions(
            entry,
            cutoff
          ) <= 0
      )
      .sort(compareCurriculumPositions)
      .flatMap(
        (entry) =>
          entry.graphemes || []
      );

  return uniqueGraphemes(
    introduced
  );
}
